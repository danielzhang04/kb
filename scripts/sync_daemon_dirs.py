"""Mirror main-authored, daemon-read paths onto the `ops` branch.

The kb-dashboard daemon reads `agents/`, every `orgs/*/workflows/` tree, and the
model/runtime registry `governance/model-routing.yaml` from its ops-branch
worktree, but that content is authored and merged on `main`. Left
alone, ops silently drifts behind main (this happened twice, fixed by hand as ops
commits a93a140 and 63b1922). This script makes the mirror a repeatable operation
modelled on the trusted `scripts/sync_skills.py` pattern:

  * `--check` — read-only drift report (exit nonzero on drift). Compares main
    against the on-disk ops checkout when it exists, else against `origin/ops`
    directly so it is safe to run from the cloud with no worktree present. Both
    modes fetch first and CRLF/LF-normalize content, so they always agree.
  * default / `--sync` — in the ops worktree, follow the constitution's ops-write
    protocol (fetch main, pull --rebase, checkout main content, commit-if-changed
    SCOPED to the mirrored paths, push, retry once) to bring ops back in line with
    main. Never deletes ops-only files unless `--prune` is passed. A rebase that
    conflicts is aborted cleanly rather than left in the daemon's worktree.

Adding another daemon-read path later is a one-line edit to DAEMON_READ_DIRS: a
trailing "/" makes the entry a directory prefix, no trailing "/" makes it one
exact file. deploy/apply_ops_reconciliation.py#RECONCILED must admit whatever is
added (tests/test_apply_ops_reconciliation.py pins the two lists together), or
the mirror commit reaches ops and is then refused on its way to the VM.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

# --- Config -----------------------------------------------------------------
# Paths the daemon reads from its ops worktree but that are authored on main.
# Trailing "/" marks a directory prefix; an entry WITHOUT one is a single exact
# file; "*" matches exactly one path segment. Add a new daemon-read path here and
# every mode picks it up.
#
# governance/model-routing.yaml is a file entry, not the governance/ tree: it is
# the registry dashboard/server/control/environment.ts#loadExecutionProfiles
# compiles the `manager:<runtime>:<model>` / `worker:<runtime>:<model>` catalogue
# from, read out of the daemon's ops checkout. When it drifts behind main, every
# launch whose assignment names a newer model is refused 400
# assigned-profile-not-found. Nothing else under governance/ is daemon-read, and
# nothing else under governance/ is mirrored.
DAEMON_READ_DIRS = [
    "agents/",
    "orgs/*/workflows/",
    "governance/model-routing.yaml",
]

DEFAULT_OPS_ROOT = Path(r"C:\Users\danie\kb-worktrees\dashboard-ops")
DEFAULT_MAIN_REF = "origin/main"
DEFAULT_OPS_REF = "origin/ops"

COMMIT_MSG = (
    "chore(ops): mirror daemon-read paths from main "
    "(agents + workflows + model-routing)\n\n"
    "Generated by scripts/sync_daemon_dirs.py --sync."
)


# --- Path matching ----------------------------------------------------------
def _is_file_entry(pattern: str) -> bool:
    """True for a DAEMON_READ_DIRS entry naming ONE file rather than a directory."""
    return not pattern.endswith("/")


def _pattern_to_regex(pattern: str) -> re.Pattern[str]:
    """Compile a DAEMON_READ_DIRS entry into a file-path matcher.

    Trailing "/" is a directory prefix (files strictly under it match); an entry
    with no trailing "/" matches that exact path and nothing below it; "*"
    matches exactly one path segment. So ``orgs/*/workflows/`` matches
    ``orgs/faceless-youtube/workflows/segments/seg.js`` but not
    ``orgs/faceless-youtube/STATE.md``, and ``governance/model-routing.yaml``
    matches only itself -- never ``governance/risk-tiers.md``, and never a
    ``governance/model-routing.yaml/...`` path.
    """
    body = re.escape(pattern.rstrip("/")).replace(r"\*", "[^/]+")
    if _is_file_entry(pattern):
        return re.compile("^" + body + "$")
    return re.compile("^" + body + "/.+$")


def _compile(patterns: list[str]) -> list[re.Pattern[str]]:
    return [_pattern_to_regex(p) for p in patterns]


def _matches(path: str, matchers: list[re.Pattern[str]]) -> bool:
    return any(m.match(path) for m in matchers)


def _pattern_depth(pattern: str) -> int:
    """Segment count of a pattern's directory prefix (``orgs/*/workflows`` -> 3)."""
    return pattern.rstrip("/").count("/") + 1


# --- Git plumbing -----------------------------------------------------------
def _git(cwd: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", "-C", str(cwd), *args],
        capture_output=True,
        text=True,
        check=check,
    )


def _list_ref(repo_root: Path, ref: str, matchers: list[re.Pattern[str]]) -> dict[str, str]:
    """Return ``{path: blob_sha}`` for daemon-read files present in ``ref``.

    Uses ``git ls-tree`` so no checkout is needed and comparison is line-ending
    immune (git blob ids are computed over the normalized stored bytes).
    """
    out = _git(repo_root, "ls-tree", "-r", "-z", ref).stdout
    files: dict[str, str] = {}
    for entry in out.split("\0"):
        if not entry:
            continue
        meta, _, path = entry.partition("\t")
        parts = meta.split()
        if len(parts) < 3 or parts[1] != "blob":
            continue
        if _matches(path, matchers):
            files[path] = parts[2]
    return files


def _read_ref_blob(repo_root: Path, ref: str, path: str) -> bytes:
    return subprocess.run(
        ["git", "-C", str(repo_root), "show", f"{ref}:{path}"],
        capture_output=True,
        check=True,
    ).stdout


def _split_ref(ref: str) -> tuple[str, str] | None:
    """Split ``origin/main`` -> (``origin``, ``main``) so we can fetch it.

    Returns None for a ref with no remote prefix (a bare local branch), which
    cannot be fetched — the caller then works from whatever the ref points at.
    """
    remote, sep, branch = ref.partition("/")
    if not sep or not branch:
        return None
    return remote, branch


def _fetch_ref(repo_root: Path, ref: str, *, required: bool) -> bool:
    """Refresh ``ref`` in ``repo_root``'s refs before it is read/checked out.

    This is the fix for the stale-local-ref failure: the production dashboard-ops
    worktree's ``origin/main`` is essentially never refreshed, so without this a
    sync would checkout stale content forever and a newly-merged org would crash
    the ``git checkout`` pathspec. ``required=True`` (sync) fails loudly on a
    fetch error; ``required=False`` (check) warns and proceeds on stale refs.
    Returns True if the fetch ran and succeeded.
    """
    parsed = _split_ref(ref)
    if parsed is None:
        return False
    remote, branch = parsed
    r = _git(repo_root, "fetch", remote, branch, check=False)
    if r.returncode != 0:
        msg = f"git fetch {remote} {branch} failed:\n{r.stderr.strip()}"
        if required:
            raise SystemExit(msg)
        print(f"WARNING: {msg}\n  (comparison uses possibly-stale local refs)",
              file=sys.stderr)
        return False
    return True


def _rebase_or_abort(ops_root: Path) -> None:
    """`git pull --rebase --autostash origin ops`, aborting cleanly on conflict.

    ``--autostash`` lets the rebase proceed even though the shared ops worktree
    carries unrelated uncommitted changes (staged or not) — they are stashed and
    reapplied around the rebase, never swept into the mirror commit (which is
    itself pathspec-scoped). A rebase that hits a *content* conflict would
    otherwise leave conflict markers and a .git/rebase-merge state in the very
    worktree the live daemon reads, so on any failure we best-effort
    ``git rebase --abort`` to restore a clean tree, then exit with a clear error.
    """
    r = _git(ops_root, "pull", "--rebase", "--autostash", "origin", "ops", check=False)
    if r.returncode != 0:
        # Distinguish a rebase-in-progress failure (conflict during replay) from
        # an autostash-reapply failure (rebase already finished, then the stash
        # pop conflicted). Only the former can be `git rebase --abort`-ed; saying
        # "rebase aborted" for the latter would misdescribe the worktree state.
        rebase_dir = _git(ops_root, "rev-parse", "--git-path", "rebase-merge",
                          check=False).stdout.strip()
        mid_rebase = bool(rebase_dir) and (ops_root / rebase_dir).exists()
        if mid_rebase:
            _git(ops_root, "rebase", "--abort", check=False)  # best-effort cleanup
            detail = "rebase aborted, worktree restored"
        else:
            detail = ("autostash reapply failed; the rebase itself completed but "
                      "the mirror did NOT run — inspect the ops worktree for "
                      "conflict markers or a dangling stash (git stash list)")
        raise SystemExit(
            f"git pull --rebase --autostash origin ops failed ({detail}):\n"
            f"{r.stderr.strip()}"
        )


def _list_disk(ops_root: Path, patterns: list[str]) -> set[str]:
    """Return posix relpaths of daemon-read files present on disk under ops_root."""
    found: set[str] = set()
    for pattern in patterns:
        pat = pattern.rstrip("/")
        for base in ops_root.glob(pat):  # glob expands ``orgs/*/workflows``
            if _is_file_entry(pattern):
                # A file entry contributes itself, never a tree walk -- this is what
                # keeps governance/model-routing.yaml from dragging governance/ in.
                if base.is_file():
                    found.add(base.relative_to(ops_root).as_posix())
            elif base.is_dir():
                for f in base.rglob("*"):
                    if f.is_file():
                        found.add(f.relative_to(ops_root).as_posix())
    return found


# --- Check (read-only drift report) -----------------------------------------
def check(
    repo_root: Path,
    patterns: list[str],
    ops_root: Path | None,
    main_ref: str = DEFAULT_MAIN_REF,
    ops_ref: str = DEFAULT_OPS_REF,
) -> dict:
    """Compare main against ops and report drift. Never writes.

    If ``ops_root`` exists on disk, compare main against that checkout (what the
    daemon actually reads). Otherwise fall back to comparing ``main_ref`` against
    ``ops_ref`` directly so the check is safe to run from the cloud.

    Refs are fetched first (best-effort; a fetch failure warns and proceeds on
    stale local refs) so the report reflects the true remote state rather than a
    never-refreshed local ``origin/main``. Both modes normalize CRLF/LF before a
    content comparison, so a CRLF checkout of logically identical content is
    never reported as drift and the two modes always agree.
    """
    matchers = _compile(patterns)
    _fetch_ref(repo_root, main_ref, required=False)
    main = _list_ref(repo_root, main_ref, matchers)
    report: dict = {"mode": "", "main_only": [], "ops_only": [], "differs": []}

    if ops_root is not None and Path(ops_root).is_dir():
        ops_root = Path(ops_root)
        report["mode"] = f"disk: {ops_root}"
        disk = _list_disk(ops_root, patterns)
        for path in sorted(main):
            target = ops_root / path
            if not target.exists():
                report["main_only"].append(path)
            else:
                main_b = _read_ref_blob(repo_root, main_ref, path).replace(b"\r\n", b"\n")
                disk_b = target.read_bytes().replace(b"\r\n", b"\n")
                if main_b != disk_b:
                    report["differs"].append(path)
        for path in sorted(disk):
            if path not in main:
                report["ops_only"].append(path)
    else:
        report["mode"] = f"refs: {main_ref} vs {ops_ref}"
        _fetch_ref(repo_root, ops_ref, required=False)
        ops = _list_ref(repo_root, ops_ref, matchers)
        for path, sha in sorted(main.items()):
            if path not in ops:
                report["main_only"].append(path)
            elif ops[path] != sha:
                # SHAs differ, but git may store one side CRLF and the other LF.
                # Compare normalized content so refs mode agrees with disk mode.
                main_b = _read_ref_blob(repo_root, main_ref, path).replace(b"\r\n", b"\n")
                ops_b = _read_ref_blob(repo_root, ops_ref, path).replace(b"\r\n", b"\n")
                if main_b != ops_b:
                    report["differs"].append(path)
        for path in sorted(ops):
            if path not in main:
                report["ops_only"].append(path)
    return report


def has_drift(report: dict) -> bool:
    return bool(report["main_only"] or report["ops_only"] or report["differs"])


# --- Sync (ops-write; follows the constitution's ops protocol) --------------
def _checkout_pathspecs(
    repo_root: Path, ref: str, patterns: list[str], matchers: list[re.Pattern[str]]
) -> list[str]:
    """Concrete pathspecs to hand to ``git checkout <ref> -- ...``.

    Derived from the files present in ``ref`` so globs like ``orgs/*/workflows``
    expand to the actual org dirs (``orgs/faceless-youtube/workflows``, ...); a
    file entry expands to that one path. A directory pathspec checkout
    adds/updates the ref's files but leaves ops-only files untouched — deletion
    is gated behind --prune.
    """
    main = _list_ref(repo_root, ref, matchers)
    specs: set[str] = set()
    for path in main:
        for pattern, matcher in zip(patterns, matchers):
            if not matcher.match(path):
                continue
            if _is_file_entry(pattern):
                specs.add(path)  # a file entry checks out exactly itself
            else:
                segs = path.split("/")
                specs.add("/".join(segs[: _pattern_depth(pattern)]))
    return sorted(specs)


def sync(
    repo_root: Path,
    patterns: list[str],
    ops_root: Path,
    main_ref: str = DEFAULT_MAIN_REF,
    prune: bool = False,
) -> dict:
    """Bring the ops worktree's daemon-read paths in line with main.

    Follows the constitution's ops-write protocol: pull --rebase, copy main's
    content in, commit only if something changed, push, retry once on a rejected
    push after re-rebasing. Ops-only files are reported and left in place unless
    ``prune`` is set. Returns a summary dict.

    ``repo_root`` is accepted for call-site symmetry with ``check()`` but is
    intentionally NOT read: every git operation (fetch, rebase, ls-tree,
    checkout) runs inside ``ops_root`` so the enumerated pathspecs always match
    the freshly-fetched refs we check out from.
    """
    ops_root = Path(ops_root)
    if not ops_root.is_dir():
        raise SystemExit(f"sync requires an ops worktree at {ops_root} (not found)")
    matchers = _compile(patterns)
    result: dict = {"pushed": False, "committed": False, "pruned": [], "kept_ops_only": []}

    # 0. Refresh main in THIS worktree's refs. Without it the ops worktree's
    #    never-refreshed origin/main means we would mirror stale content forever
    #    and a newly-merged org would crash the checkout below on a bad pathspec.
    _fetch_ref(ops_root, main_ref, required=True)

    # 1. Rebase onto the latest ops, aborting cleanly on conflict so we never
    #    leave a half-rebased tree in the worktree the live daemon reads.
    _rebase_or_abort(ops_root)

    # 2. Copy main's version of every daemon-read path into the ops worktree.
    #    Enumerate the pathspecs and the main file set from ops_root's refs —
    #    the SAME refs we just fetched and check out from — not the caller's
    #    (possibly un-fetched, different-cwd) repo_root. Reading a stale
    #    repo_root here would silently skip a brand-new org and re-open the very
    #    drift class this tool exists to kill.
    pathspecs = _checkout_pathspecs(ops_root, main_ref, patterns, matchers)
    if pathspecs:
        _git(ops_root, "checkout", main_ref, "--", *pathspecs)

    # 3. Handle ops-only files: prune (explicit) or report + keep (default).
    main_files = _list_ref(ops_root, main_ref, matchers)
    ops_only = sorted(p for p in _list_disk(ops_root, patterns) if p not in main_files)
    if prune and ops_only:
        _git(ops_root, "rm", "--quiet", "--", *ops_only)
        result["pruned"] = ops_only
    else:
        result["kept_ops_only"] = ops_only

    # 4. Stage, detect changes, and commit — all SCOPED to the mirrored paths.
    #    The shared ops worktree carries unrelated untracked files (e.g.
    #    .playwright-mcp/) and may have unrelated staged changes; a bare
    #    `git status` / `git commit` would either crash an in-sync run (empty
    #    index but dirty status) or sweep foreign changes into the mirror commit.
    #    (git rm already staged any pruned deletions, so `add` covers only the
    #    mirrored dirs; commit_specs unions in ops_only for prunes whose dir is
    #    not itself a mirrored pathspec.)
    if pathspecs:
        _git(ops_root, "add", "--", *pathspecs)
    commit_specs = sorted(set(pathspecs) | set(ops_only))
    if not commit_specs:
        return result  # no daemon-read paths to mirror — nothing to do.
    status = _git(ops_root, "status", "--porcelain", "--", *commit_specs).stdout.strip()
    if not status:
        return result  # ops already matches main — nothing to push.

    _git(ops_root, "commit", "-m", COMMIT_MSG, "--", *commit_specs)
    result["committed"] = True

    # 5. Push, retrying once after a clean re-rebase on rejection.
    push = _git(ops_root, "push", "origin", "ops", check=False)
    if push.returncode != 0:
        _rebase_or_abort(ops_root)
        _git(ops_root, "push", "origin", "ops")
    result["pushed"] = True
    return result


# --- CLI --------------------------------------------------------------------
def _print_check(report: dict) -> None:
    print(f"sync_daemon_dirs --check ({report['mode']})")
    if not has_drift(report):
        print("  clean — ops matches main for all daemon-read paths")
        return
    for label, key, hint in (
        ("main-only (missing from ops)", "main_only", "run --sync"),
        ("content-differs", "differs", "run --sync"),
        ("ops-only (extra on ops)", "ops_only", "run --sync --prune to remove"),
    ):
        if report[key]:
            print(f"  {label} [{hint}]:")
            for path in report[key]:
                print(f"    - {path}")


def _print_sync(result: dict) -> None:
    if result["pruned"]:
        print(f"  pruned {len(result['pruned'])} ops-only file(s):")
        for path in result["pruned"]:
            print(f"    - {path}")
    elif result["kept_ops_only"]:
        print(f"  kept {len(result['kept_ops_only'])} ops-only file(s) "
              "(pass --prune to remove):")
        for path in result["kept_ops_only"]:
            print(f"    - {path}")
    if not result["committed"]:
        print("  no changes — ops already matches main")
    else:
        print("  committed daemon-read paths from main; "
              f"pushed={result['pushed']}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Mirror main-authored daemon-read paths onto the ops branch."
    )
    ap.add_argument("--check", action="store_true",
                    help="read-only drift report; exit nonzero on drift; no writes")
    ap.add_argument("--sync", action="store_true",
                    help="mirror main content onto ops (default action)")
    ap.add_argument("--ops-root", type=Path, default=DEFAULT_OPS_ROOT,
                    help="ops worktree path (default: the dashboard-ops worktree)")
    ap.add_argument("--repo-root", type=Path, default=None,
                    help="repo whose git refs are queried (default: cwd)")
    ap.add_argument("--main-ref", default=DEFAULT_MAIN_REF)
    ap.add_argument("--ops-ref", default=DEFAULT_OPS_REF)
    ap.add_argument("--prune", action="store_true",
                    help="in --sync, git rm ops-only files under the mirrored paths "
                         "that are not on main (WARNING: this DELETES an ops-staged "
                         "workflow/agent still awaiting its main merge)")
    args = ap.parse_args(argv)

    repo_root = args.repo_root or Path.cwd()

    if args.check:
        report = check(repo_root, DAEMON_READ_DIRS, args.ops_root,
                       args.main_ref, args.ops_ref)
        _print_check(report)
        return 1 if has_drift(report) else 0

    result = sync(repo_root, DAEMON_READ_DIRS, args.ops_root,
                  args.main_ref, args.prune)
    print(f"sync_daemon_dirs --sync (ops worktree: {args.ops_root})")
    _print_sync(result)
    return 0


if __name__ == "__main__":
    sys.exit(main())
