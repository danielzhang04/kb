    event = read_event("sess-tail", tmp_path, pdf)
    event["transcript_path"] = str(transcript)
    r = run_hook(tmp_path, event, store_dir)
    assert r.returncode == 2
    assert b"[context-guard BLOCK]" in r.stderr


