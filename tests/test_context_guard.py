def test_transcript_tail_uses_last_occurrence_within_the_tail_not_the_head(tmp_path):
    """A huge transcript: a decoy (allowed) model near byte 0, the real (denied) model only in the
    last 64 KB. Getting this right is only possible with a TAIL read, not a head-capped read --
    a head-capped read would see the decoy and wrongly allow."""
    store_dir = tmp_path / "store"
    transcript = tmp_path / "big.jsonl"
    lines = ['{"message":{"model":"claude-sonnet-5"}}']
    lines += ["x" * 200] * 2000  # far more than 64 KB of padding
    lines.append('{"message":{"model":"claude-fable-5-1"}}')
    transcript.write_text("\n".join(lines) + "\n", encoding="utf-8")
    assert transcript.stat().st_size > 128 * 1024

    pdf = tmp_path / "doc.pdf"
    pdf.write_bytes(b"%PDF-1.4 fake")
    event = read_event("sess-huge", tmp_path, pdf)
    event["transcript_path"] = str(transcript)
    r = run_hook(tmp_path, event, store_dir)
    assert r.returncode == 2  # the tail's fable note wins, not the head's sonnet decoy


def test_transcript_tail_model_is_cached_into_store(tmp_path):
    store_dir = tmp_path / "store"
    transcript = tmp_path / "session.jsonl"
    write_transcript(transcript, ['{"message":{"model":"claude-fable-5-1"}}'])
    pdf = tmp_path / "doc.pdf"
    pdf.write_bytes(b"%PDF-1.4 fake")
    event = read_event("sess-cache", tmp_path, pdf)
    event["transcript_path"] = str(transcript)

    r1 = run_hook(tmp_path, event, store_dir)
    assert r1.returncode == 2

    # Remove the transcript entirely: if the model was NOT cached, this now falls back to
    # "no model note anywhere" and would ALLOW -- so a deny here proves the cache wrote through.
    transcript.unlink()
    r2 = run_hook(tmp_path, event, store_dir)
    assert r2.returncode == 2

    store_file = store_dir / "sess-cache.ctx.md"
    assert "claude-fable-5-1" in store_file.read_text(encoding="utf-8")


